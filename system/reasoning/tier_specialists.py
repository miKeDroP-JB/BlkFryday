# BASE SPECIALIST
# ═══════════════════════════════════════════════════════════════════════════════

class TierSpecialist(ABC):
    """Base class for all tier specialists"""

    def __init__(self, tier: Tier):
        self.tier = tier
        self.name = self._get_name()
        self.data_sources = DataSourceRegistry.get_sources(tier)
        self.insight_cache: List[Insight] = []
        self.query_count = 0
        self.total_confidence = 0.0

    @abstractmethod
    def _get_name(self) -> str:
        pass

    @abstractmethod
    def _get_capabilities(self) -> List[str]:
        pass

    @abstractmethod
    def analyze(self, query: Query) -> Insight:
        """Analyze a query and produce an insight"""
        pass

    @abstractmethod
    def _reasoning_patterns(self) -> List[Callable]:
        """Return tier-specific reasoning patterns"""
        pass

    def get_average_confidence(self) -> float:
        if self.query_count == 0:
            return 0.0
        return self.total_confidence / self.query_count

    def _record_insight(self, insight: Insight):
        self.insight_cache.append(insight)
        if len(self.insight_cache) > 100:
            self.insight_cache = self.insight_cache[-100:]
        self.query_count += 1
        self.total_confidence += insight.confidence

    def get_recent_insights(self, limit: int = 10) -> List[Insight]:
        return self.insight_cache[-limit:]

    def describe(self) -> str:
        capabilities = self._get_capabilities()
        sources = [s.name for s in self.data_sources]
        return f"""
{self.name} (Tier {self.tier.value}: {self.tier.name})
Capabilities: {', '.join(capabilities)}
Data Sources: {', '.join(sources)}
Queries Processed: {self.query_count}
Average Confidence: {self.get_average_confidence():.2%}
"""


