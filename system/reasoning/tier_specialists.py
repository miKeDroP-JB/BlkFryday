class Tier(Enum):
    LOGIC_CORE = 1      # AXIOM
    STRATEGIST = 2      # ORACLE
    MANIPULATOR = 3     # SPHINX
    ARCHITECT = 4       # DAEDALUS
    RAW_REALITY = 5     # WITNESS


@dataclass
class DataSource:
    """A curated data source for training/reference"""
    name: str
    tier: Tier
    source_type: str          # corpus, api, archive, live_feed
    description: str
    access_pattern: str       # batch, stream, query
    quality_score: float = 0.8
    update_frequency: str = "static"  # static, daily, realtime
    credentials_required: bool = False
    metadata: Dict = field(default_factory=dict)


@dataclass
class Insight:
    """An insight generated by a specialist"""
    content: str
    tier: Tier
    confidence: float
    reasoning_chain: List[str]
    sources_used: List[str]
    cross_tier_relevance: Dict[Tier, float] = field(default_factory=dict)
    timestamp: datetime = field(default_factory=datetime.utcnow)

    def to_dict(self) -> Dict:
        return {
            'content': self.content,
            'tier': self.tier.name,
            'confidence': self.confidence,
            'reasoning_chain': self.reasoning_chain,
            'sources_used': self.sources_used,
            'cross_tier_relevance': {t.name: v for t, v in self.cross_tier_relevance.items()},
            'timestamp': self.timestamp.isoformat()
        }


@dataclass
class Query:
    """A query to be processed by specialists"""
    content: str
    context: Dict = field(default_factory=dict)
    target_tiers: List[Tier] = field(default_factory=list)
    require_synthesis: bool = True
    max_depth: int = 3
    timestamp: datetime = field(default_factory=datetime.utcnow)


@dataclass
class SynthesisResult:
    """Result of cross-tier synthesis"""
    query: Query
    insights: List[Insight]
    synthesis: str
    confidence: float
    tier_contributions: Dict[Tier, float]
    emergent_patterns: List[str]
    processing_time_ms: float


