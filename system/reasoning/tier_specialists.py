# TIER COUNCIL - Cross-Tier Synthesis
# ═══════════════════════════════════════════════════════════════════════════════

class TierCouncil:
    """
    Orchestrates cross-tier synthesis through the Tournament Brain pattern.
    All five specialists deliberate on complex queries.
    """

    def __init__(self):
        self.axiom = AXIOM()
        self.oracle = ORACLE()
        self.sphinx = SPHINX()
        self.daedalus = DAEDALUS()
        self.witness = WITNESS()

        self.specialists = {
            Tier.LOGIC_CORE: self.axiom,
            Tier.STRATEGIST: self.oracle,
            Tier.MANIPULATOR: self.sphinx,
            Tier.ARCHITECT: self.daedalus,
            Tier.RAW_REALITY: self.witness,
        }

        self.synthesis_history: List[SynthesisResult] = []

    def query(self, content: str, context: Dict = None,
             target_tiers: List[Tier] = None) -> SynthesisResult:
        """
        Query the council and synthesize insights across tiers.

        Args:
            content: Query content
            context: Additional context
            target_tiers: Specific tiers to query (None = all)

        Returns:
            SynthesisResult with cross-tier synthesis
        """
        start_time = datetime.utcnow()
        context = context or {}
        target_tiers = target_tiers or list(self.specialists.keys())

        query = Query(
            content=content,
            context=context,
            target_tiers=target_tiers,
            require_synthesis=True
        )

        # Gather insights from each tier
        insights = []
        for tier in target_tiers:
            specialist = self.specialists[tier]
            insight = specialist.analyze(query)
            insights.append(insight)

        # Calculate tier contributions
        tier_contributions = self._calculate_contributions(insights)

        # Synthesize across tiers
        synthesis = self._synthesize(query, insights, tier_contributions)

        # Detect emergent patterns
        emergent = self._detect_emergent_patterns(insights)

        # Calculate overall confidence
        confidence = self._calculate_synthesis_confidence(insights, tier_contributions)

        # Calculate processing time
        processing_time = (datetime.utcnow() - start_time).total_seconds() * 1000

        result = SynthesisResult(
            query=query,
            insights=insights,
            synthesis=synthesis,
            confidence=confidence,
            tier_contributions=tier_contributions,
            emergent_patterns=emergent,
            processing_time_ms=processing_time
        )

        self.synthesis_history.append(result)

        return result

    def _calculate_contributions(self, insights: List[Insight]) -> Dict[Tier, float]:
        """Calculate each tier's contribution to the synthesis"""
        contributions = {}
        total_confidence = sum(i.confidence for i in insights)

        for insight in insights:
            if total_confidence > 0:
                contributions[insight.tier] = insight.confidence / total_confidence
            else:
                contributions[insight.tier] = 1.0 / len(insights)

        return contributions

    def _synthesize(self, query: Query, insights: List[Insight],
                   contributions: Dict[Tier, float]) -> str:
        """Synthesize insights across tiers"""
        # Weight insights by contribution
        weighted_insights = sorted(
            insights,
            key=lambda i: contributions.get(i.tier, 0),
            reverse=True
        )

        # Build synthesis
        parts = []

        # Lead with highest-contributing tier
        if weighted_insights:
            lead = weighted_insights[0]
            parts.append(f"Primary ({lead.tier.name}): {lead.content}")

        # Add supporting insights
        for insight in weighted_insights[1:3]:
            parts.append(f"Supporting ({insight.tier.name}): {insight.content}")

        # Cross-reference check
        cross_refs = self._find_cross_references(insights)
        if cross_refs:
            parts.append(f"Cross-tier validation: {cross_refs[0]}")

        return " | ".join(parts)

    def _find_cross_references(self, insights: List[Insight]) -> List[str]:
        """Find where multiple tiers agree or connect"""
        cross_refs = []

        for i, insight1 in enumerate(insights):
            for insight2 in insights[i+1:]:
                # Check cross-tier relevance
                relevance = insight1.cross_tier_relevance.get(insight2.tier, 0)
                if relevance > 0.6:
                    cross_refs.append(
                        f"{insight1.tier.name} → {insight2.tier.name} (relevance: {relevance:.0%})"
                    )

        return cross_refs

    def _detect_emergent_patterns(self, insights: List[Insight]) -> List[str]:
        """Detect patterns that emerge from cross-tier analysis"""
        patterns = []

        # Check for high-confidence consensus
        high_conf = [i for i in insights if i.confidence > 0.7]
        if len(high_conf) >= 3:
            patterns.append("Strong multi-tier consensus detected")

        # Check for tier conflicts
        confidences = [i.confidence for i in insights]
        if max(confidences) - min(confidences) > 0.4:
            patterns.append("Significant tier divergence - investigate")

        # Check for cross-tier reinforcement
        for insight in insights:
            high_relevance = [t for t, r in insight.cross_tier_relevance.items() if r > 0.7]
            if len(high_relevance) >= 2:
                patterns.append(f"{insight.tier.name} strongly connects {len(high_relevance)} tiers")

        return patterns

    def _calculate_synthesis_confidence(self, insights: List[Insight],
                                       contributions: Dict[Tier, float]) -> float:
        """Calculate confidence in the overall synthesis"""
        # Weighted average of confidences
        weighted_sum = sum(
            i.confidence * contributions.get(i.tier, 0)
            for i in insights
        )

        # Boost for consensus
        confidences = [i.confidence for i in insights]
        variance = sum((c - weighted_sum) ** 2 for c in confidences) / len(confidences)
        consensus_boost = max(0, 0.1 - variance)

        return min(1.0, weighted_sum + consensus_boost)

    def describe_council(self) -> str:
        """Describe the council and its specialists"""
        lines = [
            "╔══════════════════════════════════════════════════════════════════════╗",
            "║                        TIER COUNCIL                                  ║",
            "╚══════════════════════════════════════════════════════════════════════╝",
            ""
        ]

        for tier, specialist in self.specialists.items():
            lines.append(specialist.describe())
            lines.append("")

        lines.append(f"Total Syntheses: {len(self.synthesis_history)}")

        return "\n".join(lines)


