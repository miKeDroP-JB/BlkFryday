// List exports
export async function GET() {
  try {
    const { readdir } = await import('fs/promises');

    if (!existsSync(OUTPUT_DIR)) {
      return NextResponse.json({
        success: true,
        data: { exports: [] }
      });
    }

    const exports = await readdir(OUTPUT_DIR);

    return NextResponse.json({
      success: true,
      data: {
        exports: exports.map(name => ({
          id: name,
          url: `/exports/${name}`,
          indexUrl: `/exports/${name}/index.html`
        }))
      }
    });
  } catch (error) {
    return NextResponse.json({
      success: false,
      error: error.message
    }, { status: 500 });
  }
}
